CREATE TABLE post_press
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT         NOT NULL,
    quantity    INTEGER        NOT NULL,
    width_cm    NUMERIC(12, 3) NOT NULL,
    length_cm   NUMERIC(12, 3) NOT NULL,
    total_price NUMERIC(19, 2) NOT NULL,
    created_at  TIMESTAMP      NOT NULL,
    CONSTRAINT fk_post_press_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE printing
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT         NOT NULL,
    papier      VARCHAR(50)    NOT NULL,
    colour      VARCHAR(10)    NOT NULL,
    quantity    INTEGER        NOT NULL,
    total_cost  NUMERIC(19, 2) NOT NULL,
    created_at  TIMESTAMP      NOT NULL,
    CONSTRAINT fk_printing_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE cliche
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT         NOT NULL,
    quantity    INTEGER        NOT NULL,
    width_cm    NUMERIC(12, 3) NOT NULL,
    length_cm   NUMERIC(12, 3) NOT NULL,
    total_price NUMERIC(19, 2) NOT NULL,
    created_at  TIMESTAMP      NOT NULL,
    CONSTRAINT fk_cliche_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE customer_orders
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT         NOT NULL,
    product        VARCHAR(255)   NOT NULL,
    postpress_price NUMERIC(19, 2) NOT NULL,
    printing_price NUMERIC(19, 2) NOT NULL,
    cliche_price   NUMERIC(19, 2) NOT NULL,
    total_cost     NUMERIC(19, 2) NOT NULL,
    status         VARCHAR(20)    NOT NULL,
    created_at     TIMESTAMP      NOT NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE INDEX idx_post_press_customer ON post_press (customer_id);
CREATE INDEX idx_printing_customer ON printing (customer_id);
CREATE INDEX idx_cliche_customer ON cliche (customer_id);
CREATE INDEX idx_orders_customer ON customer_orders (customer_id);
CREATE INDEX idx_orders_status ON customer_orders (status);

CREATE TABLE material
(
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255)   NOT NULL,
    unit  VARCHAR(10)    NOT NULL,
    stock NUMERIC(19, 3) NOT NULL,
    note  VARCHAR(255),
    CONSTRAINT uq_material_name UNIQUE (name)
);

CREATE TABLE stock_movement
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id   BIGINT         NOT NULL,
    movement_type VARCHAR(10)    NOT NULL,
    quantity      NUMERIC(19, 3) NOT NULL,
    note          VARCHAR(255),
    created_at    TIMESTAMP      NOT NULL,
    CONSTRAINT fk_movement_material FOREIGN KEY (material_id) REFERENCES material (id)
);

CREATE INDEX idx_movement_material ON stock_movement (material_id);
