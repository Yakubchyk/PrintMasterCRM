CREATE TABLE customer
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255) NOT NULL,
    email        VARCHAR(255) NOT NULL,
    CONSTRAINT uq_customer_name UNIQUE (name),
    CONSTRAINT uq_customer_phone UNIQUE (phone_number),
    CONSTRAINT uq_customer_email UNIQUE (email)
);

CREATE TABLE setting
(
    id                   BIGINT PRIMARY KEY,
    length_unit          VARCHAR(10)    NOT NULL,
    montage_work_price   NUMERIC(19, 2) NOT NULL,
    one_ottisk_price     NUMERIC(19, 2) NOT NULL,
    foil_price           NUMERIC(19, 4) NOT NULL,
    foil_area_unit       VARCHAR(10)    NOT NULL,
    price_print          NUMERIC(19, 4) NOT NULL,
    cliche_price         NUMERIC(19, 4) NOT NULL,
    cliche_area_unit     VARCHAR(10)    NOT NULL,
    cliche_min_price     NUMERIC(19, 2) NOT NULL,
    markup               NUMERIC(10, 4) NOT NULL
);

