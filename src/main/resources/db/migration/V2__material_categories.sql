-- Склад: разделы вместо свободных единиц, размер листа и списание материалов на заказ.
ALTER TABLE material ADD COLUMN category VARCHAR(20) DEFAULT 'PAPER' NOT NULL;
ALTER TABLE material ADD COLUMN sheet_size VARCHAR(50);
ALTER TABLE material DROP COLUMN unit;

CREATE TABLE order_material
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT         NOT NULL,
    material_id BIGINT         NOT NULL,
    quantity    NUMERIC(19, 3) NOT NULL,
    CONSTRAINT fk_order_material_order FOREIGN KEY (order_id) REFERENCES customer_orders (id),
    CONSTRAINT fk_order_material_material FOREIGN KEY (material_id) REFERENCES material (id)
);

CREATE INDEX idx_order_material_order ON order_material (order_id);
CREATE INDEX idx_order_material_material ON order_material (material_id);
